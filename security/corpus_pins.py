"""Corpus pins (Deliverable 2): the data and policy files the service trusts are pinned by SHA-256.

    python -m security.corpus_pins            # verify every pin; exit 1 on any mismatch or missing file
    python -m security.corpus_pins --write    # after a REVIEWED change: re-pin and commit the new pins file

Week 8 pinned the prompts (prompts/pin.json). This extends the same idea to everything else the model or the
tools read as truth: the clinic registry the MCP server serves, the allowlist that limits it, the partner
URLs, the secret references, the golden set the eval gate scores against, and the prompt pin file itself.
A file edited in place (a poisoned clinic record, a widened allowlist, a cleartext partner URL) no longer
matches its pin, so the API and the MCP server refuse to start and CI fails, until someone re-pins it in a
reviewed commit. That turns a silent edit into a visible diff with an author.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINS_PATH = ROOT / "security" / "corpus_pins.json"

PINNED_FILES = {
    "clinics.json": "MCP clinic registry and stock (what check_stock and find_clinics answer from)",
    "clinics_allowlist.json": "which clinics each MCP caller may see",
    "config/partners.yaml": "outbound partner URLs (transit policy input)",
    "config/triage.yaml": "release config: model, prompt routing, MCP version",
    "prompts/pin.json": "prompt lockfile (it pins each prompt's SHA-256 in turn)",
    "security/secret_refs.yaml": "where secrets come from and what counts as a placeholder",
    "evals/golden.jsonl": "labelled cases the eval gate and the injection false-positive check use",
}

# What the running service reads. The image does not ship evals/, so the golden set is checked in CI only.
RUNTIME_FILES = [n for n in PINNED_FILES if not n.startswith("evals/")]


class PinMismatch(RuntimeError):
    """A pinned file is missing or its bytes changed since it was pinned."""


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_pins(path: Path = PINS_PATH) -> dict[str, dict]:
    return json.loads(path.read_text(encoding="utf-8"))["files"]


def check(names: list[str] | None = None, root: Path = ROOT,
          pins_path: Path = PINS_PATH) -> list[tuple[str, bool, str]]:
    pins = load_pins(pins_path)
    out = []
    for name in names or list(pins):
        if name not in pins:
            out.append((name, False, "not pinned"))
            continue
        path = root / name
        if not path.is_file():
            out.append((name, False, "missing"))
            continue
        actual = sha256_file(path)
        ok = actual == pins[name]["sha256"]
        out.append((name, ok, actual[:12] if ok else f"changed: {actual[:12]} != pinned {pins[name]['sha256'][:12]}"))
    return out


def verify_pins(names: list[str] | None = None, root: Path = ROOT, pins_path: Path = PINS_PATH) -> None:
    """Startup guard used by the API and the MCP server."""
    bad = [f"{n} ({d})" for n, ok, d in check(names, root, pins_path) if not ok]
    if bad:
        raise PinMismatch("corpus pin mismatch, refusing to start: " + "; ".join(bad)
                          + ". If the change was reviewed, run python -m security.corpus_pins --write.")


def write_pins(root: Path = ROOT, pins_path: Path = PINS_PATH) -> None:
    pins_path.write_text(json.dumps({
        "note": "Generated by python -m security.corpus_pins --write after a reviewed change. "
                "The API and the MCP server refuse to start when a file no longer matches.",
        "files": {name: {"sha256": sha256_file(root / name), "what": what} for name, what in PINNED_FILES.items()},
    }, indent=2) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Verify (or re-pin) the SHA-256 of trusted data and policy files.")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    if args.write:
        write_pins()
        print(f"pinned {len(PINNED_FILES)} files in {PINS_PATH.relative_to(ROOT)}")
        return 0
    results = check()
    for name, ok, detail in results:
        print(f"{'PASS' if ok else 'FAIL'}  {name:<28} {detail}")
    failed = sum(not ok for _, ok, _ in results)
    print(f"{len(results) - failed}/{len(results)} pins match -> exit {1 if failed else 0}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
